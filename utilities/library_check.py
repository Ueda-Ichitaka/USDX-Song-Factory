#!/usr/bin/env python3
"""Check an UltraStar library for songs with a wrong #GAP or drifting timing.

About me: every usable song file of a library is checked with the method the
stack's gap/sync repair uses: the song file's own lyrics are aligned to its
separated vocals in one pass (stack/orchestrator/repair.global_line_points())
and timing_fit gives how far the file is shifted, how much the shift grows
over the song (drift: wrong #BPM or another audio version), how many lines
agree - and the #GAP (and #BPM) that would fix it. Runs inside the stack's
container (it needs demucs and the aligner); start it with
run_library_check.sh, which mounts the library read-only.

Left out: duets, relative timing, songs without audio or with fewer than 50
notes, and songs this stack generated. Aligner language: the file's
#LANGUAGE (first entry); romanized lyrics use the English model (marked
less reliable); without #LANGUAGE whisper tiny detects it.

Every WORKER_SONGS songs run in a fresh worker process (one long process
grew to 10 GB after 140 songs); a worker that dies gets its song marked as
an error and the next worker goes on. Before each song the run waits until
MIN_AVAIL_GB of RAM are free and the load is below MAX_LOAD. The audio
cache of a song is deleted once it is checked.

Output in ANALYSIS_DIR: results.jsonl (one JSON line per song file, the
newest line per song counts; resumable) and library-check.txt (the report,
rewritten after every worker). Songs are checked in a seeded random order,
so a partial run is already a fair sample.

Settings (environment): LIBRARY_DIR (required, mounted at the same path as
on the host), ANALYSIS_DIR (default /data/analysis), WORK_DIR (default
/data/work/library-check), MIN_AVAIL_GB (8), MAX_LOAD (14), THREADS (4),
WORKER_SONGS (10), ONLY (only songs whose name contains this - tests),
RETRY_ERRORS=1 (check songs marked as errors again).
"""
import hashlib
import json
import os
import random
import shutil
import subprocess
import sys
import time
import traceback

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import songfile  # noqa: E402

LIBRARY_DIR = os.environ.get("LIBRARY_DIR", "")
ANALYSIS_DIR = os.environ.get("ANALYSIS_DIR", "/data/analysis")
WORK_DIR = os.environ.get("WORK_DIR", "/data/work/library-check")
MIN_AVAIL_GB = float(os.environ.get("MIN_AVAIL_GB", "8"))
MAX_LOAD = float(os.environ.get("MAX_LOAD", "14"))
THREADS = int(os.environ.get("THREADS", "4"))
WORKER_SONGS = int(os.environ.get("WORKER_SONGS", "10"))
ONLY = os.environ.get("ONLY", "")
RETRY_ERRORS = os.environ.get("RETRY_ERRORS") == "1"
ROMANIZED = ("japanese (romanized)", "korean (romanized)")
MIN_NOTES = 50


def log(msg):
    print(time.strftime("%H:%M:%S"), msg, flush=True)


def results_path():
    return os.path.join(ANALYSIS_DIR, "results.jsonl")


def report_path():
    return os.path.join(ANALYSIS_DIR, "library-check.txt")


def current_path():
    return os.path.join(ANALYSIS_DIR, "current-song.txt")


def candidates(library: str) -> list:
    """One dict per song file of the library: name, folder (relative), txt,
    skip (reason or None), lang (aligner language or None = detect), note."""
    out = []
    for folder in sorted(os.listdir(library)):
        d = os.path.join(library, folder)
        if not os.path.isdir(d):
            continue
        for path in songfile.song_txts(d):
            txt = os.path.basename(path)
            name = folder if txt[:-4] == folder else f"{folder} [{txt[:-4]}]"
            entry = {"name": name, "folder": folder, "txt": txt, "skip": None, "lang": None, "note": ""}
            try:
                song = songfile.read(path)
            except OSError as exc:
                entry["skip"] = f"unreadable: {exc}"
                out.append(entry)
                continue
            audio = song.tags.get("AUDIO") or song.tags.get("MP3") or ""
            if songfile.generated_by_stack(song.text):
                entry["skip"] = "generated by this stack"
            elif song.duet:
                entry["skip"] = "duet"
            elif song.relative:
                entry["skip"] = "relative timing"
            elif not audio or not os.path.isfile(os.path.join(d, audio)):
                entry["skip"] = "no audio file"
            elif song.notes < MIN_NOTES:
                entry["skip"] = f"fewer than {MIN_NOTES} notes"
            raw = song.tags.get("LANGUAGE", "").split(",")[0].strip().lower()
            if raw in ROMANIZED:
                entry["lang"], entry["note"] = "en", "romanized lyrics, English aligner - less reliable"
            else:
                entry["lang"] = songfile.language_code(raw) or None
            out.append(entry)
    return out


def verdict(fit) -> str:
    """good / #GAP off / drifts / unclear for a timing_fit.fit() result."""
    if not fit or fit["agree"] < 0.6:
        return "unclear"
    offset = fit["intercept"] + (fit["slope"] - 1.0) * fit["first"]
    drift = (fit["slope"] - 1.0) * (fit["last"] - fit["first"])
    if abs(drift) >= 1.0:
        return "drifts"
    if abs(offset) >= 0.4 and fit["agree"] >= 0.8:
        return "#GAP off"
    return "good"


def check_song(entry: dict, models: dict) -> dict:
    """Align one song and measure it (stack container only)."""
    sys.path.insert(0, "/app/orchestrator")
    sys.path.insert(0, "/app/UltraSinger/src")
    import repair
    import timing_fit
    folder = os.path.join(LIBRARY_DIR, entry["folder"])
    txt = repair.Txt(os.path.join(folder, entry["txt"]))
    # a short folder name: some song names are too long for a path
    work = os.path.join(WORK_DIR, hashlib.sha1(entry["name"].encode("utf-8")).hexdigest()[:16])
    try:
        audio_path, err = repair.locate_audio(folder, txt, work)
        if err:
            return {"skip": f"audio: {err}"}
        vocals, _ = repair.prepare_processing_audio(audio_path, work, "cuda")
        audio16k = repair.load_audio_16k(vocals)
        lang = entry["lang"] or repair.detect_language(vocals)
        if lang not in models:
            models[lang] = repair.load_aligner(lang, "cpu")
        model, meta, lang = models[lang]
        points = repair.global_line_points(txt, model, meta, audio16k, "cuda")
    finally:
        shutil.rmtree(work, ignore_errors=True)
    fit = timing_fit.fit(points)
    gap = txt.gap_ms or 0.0
    res = {"lang": lang, "lines": len(points), "gap_ms": gap, "bpm": txt.bpm_tag,
           "verdict": verdict(fit)}
    if fit:
        only_gap = timing_fit.correction(fit, gap, txt.bpm_tag, gap_only=True, min_agree=0.0)
        full = timing_fit.correction(fit, gap, txt.bpm_tag, min_agree=0.0)
        res.update(agree=round(fit["agree"], 3), offset_s=round(only_gap["offset_s"], 2),
                   drift_s=round(only_gap["drift_s"], 2), gap_fix_ms=round(only_gap["gap_ms"]),
                   gap_fix_with_bpm_ms=round(full["gap_ms"]), bpm_fix=round(full["bpm"], 4))
    return res


def load_rows(path: str) -> list:
    """The newest result per song."""
    rows = {}
    if os.path.isfile(path):
        for line in open(path, encoding="utf-8"):
            row = json.loads(line)
            rows[row["name"]] = row
    return list(rows.values())


def append_row(row: dict):
    with open(results_path(), "a", encoding="utf-8") as f:
        f.write(json.dumps(row, ensure_ascii=False) + "\n")


def todo_list():
    rows = load_rows(results_path())
    done = {r["name"] for r in rows
            if not (RETRY_ERRORS and r.get("skip", "").startswith("error"))}
    songs = candidates(LIBRARY_DIR)
    random.Random(20261015).shuffle(songs)
    todo = [s for s in songs if s["name"] not in done]
    if ONLY:
        todo = [s for s in todo if ONLY in s["name"]]
    return songs, todo


def write_report(rows: list, path: str, library: str):
    checked = [r for r in rows if "verdict" in r]
    skipped = [r for r in rows if "skip" in r]
    by = {k: sorted((r for r in checked if r["verdict"] == k), key=lambda r: r["name"].lower())
          for k in ("good", "#GAP off", "drifts", "unclear")}
    lines = [f"Library check - {library}",
             f"Report written {time.strftime('%Y-%m-%d %H:%M')}: {len(checked)} song files checked, "
             f"{len(skipped)} left out (reasons at the end).",
             "",
             "Per song: the song file's own lyrics aligned to its separated vocals.",
             "  lyrics ... too late / early   how far the lyrics are off at the first line",
             "  drift   how much that grows until the last line (#BPM or another audio version)",
             "  agree   share of lines that fit once shift and drift are removed",
             "  fix     the #GAP (and #BPM) that puts the lines on the singing",
             "",
             "RESULT"]
    lines += [f"  {k:10} {len(v):5}" for k, v in by.items()]
    lines.append("")
    titles = {"#GAP off": "#GAP OFF - shifting #GAP fixes it",
              "drifts": "DRIFTS - #GAP and #BPM wrong, or another audio version",
              "unclear": "UNCLEAR - fewer than 60% of the lines fit: another audio version,\n"
                         "or singing the aligner cannot follow - listen"}
    for k in ("#GAP off", "drifts", "unclear"):
        lines += ["=" * 78, f"{titles[k]} ({len(by[k])})", "=" * 78]
        for r in by[k]:
            if "offset_s" not in r:
                lines.append(f"{r['name']}\n    too few lines aligned")
                continue
            late = -r["offset_s"]  # file minus sung: positive = the lyrics come too late
            entry = (f"{r['name']}\n    lyrics {abs(late):.2f} s too {'late' if late > 0 else 'early'}, "
                     f"drift {r['drift_s']:+.2f} s, agree {r['agree']:.2f}")
            if k == "#GAP off":
                entry += f"\n    fix: #GAP {r['gap_ms']:.0f} -> {r['gap_fix_ms']}"
            elif k == "drifts":
                entry += (f"\n    fix: #GAP {r['gap_ms']:.0f} -> {r['gap_fix_with_bpm_ms']}, "
                          f"#BPM {r['bpm']} -> {r['bpm_fix']}")
            if r.get("note"):
                entry += f"\n    ({r['note']})"
            lines.append(entry)
        lines.append("")
    lines += ["=" * 78, f"GOOD ({len(by['good'])})", "=" * 78]
    lines += [r["name"] for r in by["good"]]
    lines += ["", "=" * 78, f"LEFT OUT ({len(skipped)})", "=" * 78]
    lines += [f"{r['name']}: {r['skip']}" for r in sorted(skipped, key=lambda r: r["name"].lower())]
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, path)


def worker():
    """Check up to WORKER_SONGS songs, then exit (a fresh process gives all
    memory back)."""
    import torch
    try:  # when memory runs out, the kernel kills this worker, not the run
        with open("/proc/self/oom_score_adj", "w") as f:
            f.write("1000")
    except OSError:
        pass
    torch.set_num_threads(THREADS)
    _, todo = todo_list()
    models, checked = {}, 0
    for entry in todo:
        if checked >= WORKER_SONGS:
            break
        base = {"name": entry["name"], "folder": entry["folder"], "txt": entry["txt"]}
        if entry["skip"]:
            append_row(dict(base, skip=entry["skip"]))
            continue
        wait_for_resources()
        with open(current_path(), "w", encoding="utf-8") as f:
            f.write(json.dumps(base, ensure_ascii=False))
        t0 = time.time()
        try:
            row = dict(base, **check_song(entry, models))
            if entry["note"]:
                row["note"] = entry["note"]
        except Exception as exc:  # noqa: BLE001 - one bad song must not stop the run
            traceback.print_exc()
            row = dict(base, skip=f"error: {str(exc)[:120]}")
        append_row(row)
        os.remove(current_path())
        checked += 1
        log(f"{entry['name']}: {row.get('verdict', row.get('skip'))} ({time.time() - t0:.0f} s)")


def wait_for_resources():
    """Block while the machine is short of memory or busy."""
    while True:
        avail = 0.0
        for line in open("/proc/meminfo"):
            if line.startswith("MemAvailable:"):
                avail = int(line.split()[1]) / 1024 / 1024
        load = float(open("/proc/loadavg").read().split()[0])
        if avail >= MIN_AVAIL_GB and load <= MAX_LOAD:
            return
        log(f"waiting: {avail:.1f} GB free (need {MIN_AVAIL_GB}), load {load:.1f} (max {MAX_LOAD})")
        time.sleep(60)


def mark_dead_worker(code):
    """The song a killed worker was on becomes an error row."""
    if os.path.isfile(current_path()):
        text = open(current_path(), encoding="utf-8").read().strip()
        try:
            base = json.loads(text)
        except ValueError:  # an older version wrote only the song name
            base = {"name": text}
        os.remove(current_path())
        why = ("the check was stopped while on this song" if code == "before a restart"
               else f"the check process died (exit {code}, probably out of memory)")
        append_row(dict(base, skip=f"error: {why}"))
        log(f"{base['name']}: the check process died (exit {code}) - marked, going on")


def main():
    if not LIBRARY_DIR or not os.path.isdir(LIBRARY_DIR):
        sys.exit(f"LIBRARY_DIR is not a folder: {LIBRARY_DIR!r}")
    os.makedirs(ANALYSIS_DIR, exist_ok=True)
    os.makedirs(WORK_DIR, exist_ok=True)
    mark_dead_worker("before a restart")
    songs, todo = todo_list()
    log(f"{len(songs)} song files, {len(load_rows(results_path()))} have a result, {len(todo)} to go")
    while todo:
        before = len(todo)
        proc = subprocess.run([sys.executable, os.path.abspath(__file__), "--worker"])
        mark_dead_worker(proc.returncode)
        write_report(load_rows(results_path()), report_path(), LIBRARY_DIR)
        _, todo = todo_list()
        log(f"{len(songs) - len(todo)} of {len(songs)} done")
        if len(todo) >= before:
            log("no progress - stopping")
            break
    write_report(load_rows(results_path()), report_path(), LIBRARY_DIR)
    log("LIBRARY_CHECK_DONE")


if __name__ == "__main__":
    if "--worker" in sys.argv:
        worker()
    else:
        main()
