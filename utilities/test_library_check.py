#!/usr/bin/env python3
"""Tests for library_check.py (the parts that run without the stack image).

About me: plain assert-based checks (no pytest), host only:

    python3 test_library_check.py
"""

import json
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import library_check  # noqa: E402

failures = []


def check(name, condition):
    print(f"[{'PASS' if condition else 'FAIL'}] {name}")
    if not condition:
        failures.append(name)


NOTES = "".join(f": {i * 4} 4 0 la \n" for i in range(60))


def song(lib, folder, txt, header, notes=NOTES, audio=True, bpm="300"):
    d = os.path.join(lib, folder)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, txt), "w", encoding="utf-8") as f:
        f.write(header + (f"#BPM:{bpm}\n" if bpm else "") + notes + "E\n")
    if audio:
        open(os.path.join(d, "a.mp3"), "w").close()


lib = tempfile.mkdtemp()
song(lib, "Good - Song", "Good - Song.txt", "#TITLE:Song\n#ARTIST:Good\n#MP3:a.mp3\n#LANGUAGE:German\n")
song(lib, "Duet - Song", "Duet - Song.txt", "#TITLE:Song\n#ARTIST:Duet\n#MP3:a.mp3\nP1\n")
song(lib, "Gen - Song", "Gen - Song.txt", "#TITLE:Song\n#ARTIST:Gen\n#MP3:a.mp3\n#CREATOR:UltraSinger\n")
song(lib, "NoAudio - Song", "NoAudio - Song.txt", "#TITLE:Song\n#ARTIST:NoAudio\n#MP3:missing.mp3\n")
song(lib, "Short - Song", "Short - Song.txt", "#TITLE:Song\n#ARTIST:Short\n#MP3:a.mp3\n", notes=": 0 4 0 la\n")
song(lib, "NoBpm - Song", "NoBpm - Song.txt", "#TITLE:Song\n#ARTIST:NoBpm\n#MP3:a.mp3\n", bpm=None)
song(lib, "Two - Songs", "first.txt", "#TITLE:One\n#ARTIST:Two\n#MP3:a.mp3\n#LANGUAGE:Japanese (romanized)\n")
song(lib, "Two - Songs", "second.txt", "#TITLE:Two\n#ARTIST:Two\n#MP3:a.mp3\n")
open(os.path.join(lib, "Good - Song", "lyrics.txt"), "w").write("la\n")

songs = {c["name"]: c for c in library_check.candidates(lib)}
check(f"candidates: one entry per song file (got {sorted(songs)})",
      sorted(songs) == ["Duet - Song", "Gen - Song", "Good - Song", "NoAudio - Song", "NoBpm - Song",
                        "Short - Song", "Two - Songs [first]", "Two - Songs [second]"])
check("candidates: a usable song with folder, txt and aligner language",
      songs["Good - Song"]["skip"] is None and songs["Good - Song"]["folder"] == "Good - Song"
      and songs["Good - Song"]["txt"] == "Good - Song.txt" and songs["Good - Song"]["lang"] == "de")
check("candidates: reasons to leave a song out",
      songs["Duet - Song"]["skip"] == "duet" and songs["Gen - Song"]["skip"] == "generated by this stack"
      and songs["NoAudio - Song"]["skip"] == "no audio file"
      and songs["Short - Song"]["skip"] == "fewer than 50 notes")
# USDX does not load a song file without #BPM (USong.pas: "File incomplete")
check(f"candidates: no #BPM -> left out (got {songs['NoBpm - Song']['skip']})",
      songs["NoBpm - Song"]["skip"] == "no #BPM (USDX does not load it)")

# audio that decodes to much less than its stated length: zero-filled or
# broken files (the Slayer mp3s decode 4-10 s of 280-385 s)
check("damaged_audio: decodes less than half -> the reason with both lengths",
      library_check.damaged_audio(9.84, 385.4) == "decodes only 9.8 of 385 s")
check("damaged_audio: a VBR estimate somewhat off is no damage",
      library_check.damaged_audio(250.0, 385.4) is None)
check("damaged_audio: unknown stated length -> no verdict",
      library_check.damaged_audio(9.84, None) is None)
check("candidates: romanized lyrics -> English aligner with a note; no #LANGUAGE -> detect",
      songs["Two - Songs [first]"]["lang"] == "en" and "romanized" in songs["Two - Songs [first]"]["note"]
      and songs["Two - Songs [second]"]["lang"] is None)

fit = {"slope": 1.0, "intercept": -2.0, "first": 10.0, "last": 200.0, "agree": 0.95}
check("verdict: a constant shift", library_check.verdict(fit) == "#GAP off")
check("verdict: small shift is good", library_check.verdict(dict(fit, intercept=-0.2)) == "good")
check("verdict: drift", library_check.verdict(dict(fit, slope=1.01)) == "drifts")
check("verdict: too few lines agree", library_check.verdict(dict(fit, agree=0.5)) == "unclear")
check("verdict: no fit", library_check.verdict(None) == "unclear")

out = tempfile.mkdtemp()
results = os.path.join(out, "results.jsonl")
with open(results, "w", encoding="utf-8") as f:
    f.write(json.dumps({"name": "A", "skip": "error: died"}) + "\n")
    f.write(json.dumps({"name": "A", "folder": "A", "txt": "a.txt", "verdict": "#GAP off",
                        "offset_s": 1.5, "drift_s": 0.0, "agree": 0.9, "gap_ms": 1000,
                        "gap_fix_ms": 2500}) + "\n")
    f.write(json.dumps({"name": "B", "skip": "duet"}) + "\n")
    f.write(json.dumps({"name": "C", "verdict": "damaged audio", "note": "decodes only 9.8 of 385 s"}) + "\n")
rows = library_check.load_rows(results)
check(f"load_rows: the newest result per song (got {rows})",
      len(rows) == 3 and [r for r in rows if r["name"] == "A"][0]["verdict"] == "#GAP off")
report = os.path.join(out, "report.txt")
library_check.write_report(rows, report, "/lib")
text = open(report, encoding="utf-8").read()
check("write_report: counts, the song with its fix, the left-out song",
      "#GAP off          1" in text and "A\n    lyrics 1.50 s too early" in text
      and "fix: #GAP 1000 -> 2500" in text and "B: duet" in text)
check("write_report: damaged audio counted and listed with its reason",
      "damaged audio     1" in text and "C\n    decodes only 9.8 of 385 s" in text)

# a marker left by an older version holds just the song name (not JSON)
library_check.ANALYSIS_DIR = tempfile.mkdtemp()
with open(library_check.current_path(), "w", encoding="utf-8") as f:
    f.write("Some Artist - Some Song")
library_check.mark_dead_worker("before a restart")
_rows = library_check.load_rows(library_check.results_path())
check(f"mark_dead_worker: an old plain-text marker becomes an error row (got {_rows})",
      len(_rows) == 1 and _rows[0]["name"] == "Some Artist - Some Song"
      and _rows[0]["skip"].startswith("error") and not os.path.exists(library_check.current_path()))

# RETRY_ERRORS: every song marked as an error before this run gets one new
# try; an error written during the run counts as done (a song that fails
# again must not block the rest - the run used to stop with "no progress")
_lib = tempfile.mkdtemp()
for _band in ("Old", "Again", "Fine"):
    song(_lib, f"{_band} - Song", f"{_band} - Song.txt", f"#TITLE:Song\n#ARTIST:{_band}\n#MP3:a.mp3\n")
library_check.LIBRARY_DIR = _lib
library_check.ANALYSIS_DIR = tempfile.mkdtemp()
library_check.append_row({"name": "Old - Song", "skip": "error: cannot import"})
library_check.append_row({"name": "Again - Song", "skip": "error: cannot import"})
library_check.append_row({"name": "Fine - Song", "verdict": "good"})
_start = library_check.result_lines()
library_check.append_row({"name": "Again - Song", "skip": "error: frames"})  # failed again in this run
library_check.RETRY_ERRORS = True
_, _todo = library_check.todo_list(retry_from=_start)
check(f"todo_list: an old error is retried, an error from this run is not (got {[t['name'] for t in _todo]})",
      [t["name"] for t in _todo] == ["Old - Song"])
_, _todo = library_check.todo_list(retry_from=None)
check(f"todo_list: without a start line every error is retried (got {sorted(t['name'] for t in _todo)})",
      sorted(t["name"] for t in _todo) == ["Again - Song", "Old - Song"])
library_check.RETRY_ERRORS = False
_, _todo = library_check.todo_list(retry_from=_start)
check("todo_list: without RETRY_ERRORS errors count as done", _todo == [])

# songs with audio longer than MAX_AUDIO_MIN (15) minutes are left out - a
# 44-minute live recording needed more than the 10 GB cap and took the whole
# check down with it
_entry = library_check.candidates(lib)
_good = [e for e in _entry if e["name"] == "Good - Song"][0]
check(f"candidates: a usable song names its audio file (got {_good.get('audio')})",
      _good.get("audio") == os.path.join(lib, "Good - Song", "a.mp3"))
check("length_skip: the default limit is 15 minutes", library_check.MAX_AUDIO_MIN == 15)
check("length_skip: a 44-minute recording is left out with its length",
      library_check.length_skip(_good, audio_minutes=lambda p: 44.1) == "audio longer than 15 min (44 min)")
check("length_skip: a 14-minute song is checked",
      library_check.length_skip(_good, audio_minutes=lambda p: 14.0) is None)
check("length_skip: an unknown length is checked",
      library_check.length_skip(_good, audio_minutes=lambda p: None) is None)

# a better candidate list makes older results stale: a song left out for a
# reason candidates() no longer gives is checked again, and results of
# entries that are no song files any more stay out of the report
_lib = tempfile.mkdtemp()
song(_lib, "Was - Relative", "Was - Relative.txt", "#TITLE:Relative\n#ARTIST:Was\n#MP3:a.mp3\n")
song(_lib, "Still - Duet", "Still - Duet.txt", "#TITLE:Duet\n#ARTIST:Still\n#MP3:a.mp3\nP1\n")
song(_lib, "Long - Song", "Long - Song.txt", "#TITLE:Song\n#ARTIST:Long\n#MP3:a.mp3\n")
open(os.path.join(_lib, "Long - Song", "license.txt"), "w").write("CC BY 3.0\n")
library_check.LIBRARY_DIR = _lib
library_check.ANALYSIS_DIR = tempfile.mkdtemp()
library_check.append_row({"name": "Was - Relative", "skip": "relative timing"})
library_check.append_row({"name": "Still - Duet", "skip": "duet"})
library_check.append_row({"name": "Long - Song", "skip": "audio longer than 15 min (44 min)"})
library_check.append_row({"name": "Long - Song [license]", "skip": "no audio file"})
# an error (or a verdict) of a song that candidates() now leaves out
song(_lib, "Now - NoBpm", "Now - NoBpm.txt", "#TITLE:NoBpm\n#ARTIST:Now\n#MP3:a.mp3\n", bpm=None)
library_check.append_row({"name": "Now - NoBpm", "skip": "error: type NoneType doesn't define __round__"})
_songs, _todo = library_check.todo_list()
check(f"todo_list: a song whose old reason to leave it out no longer holds is checked again "
      f"(got {[t['name'] for t in _todo]})", "Was - Relative" in [t["name"] for t in _todo])
check(f"todo_list: a song now left out whose result says otherwise is done again "
      f"(got {sorted(t['name'] for t in _todo)})",
      sorted(t["name"] for t in _todo) == ["Now - NoBpm", "Was - Relative"])
check(f"report_rows: only results of current song files (got {library_check.report_rows(_songs)})",
      sorted(r["name"] for r in library_check.report_rows(_songs)) == ["Long - Song", "Now - NoBpm",
                                                                        "Still - Duet", "Was - Relative"])

print()
if failures:
    print(f"{len(failures)} check(s) FAILED: {failures}")
    sys.exit(1)
print("all checks passed")
